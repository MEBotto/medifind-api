import { Request, Response } from 'express';
import ShiftsService from '../services/ShiftsService';
import { CreateShiftDTO, UpdateShiftDTO } from '../dtos/shift.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class ShiftsController {
  constructor(private readonly shiftsService: ShiftsService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreateShiftDTO;
      const entity = await this.shiftsService.createShift(data);
      sendCreated(res, entity, 'Shift creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Shift:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.shiftsService.getShiftById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Shift:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.shiftsService.getAllShifts();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Shifts:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdateShiftDTO;
      const entity = await this.shiftsService.updateShift(id, data);
      sendSuccess(res, entity, 'Shift actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Shift:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.shiftsService.deleteShift(id);
      sendSuccess(res, null, 'Shift eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Shift:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default ShiftsController;
