import { Request, Response } from 'express';
import CategorysService from '../services/CategorysService';
import { CreateCategoryDTO, UpdateCategoryDTO } from '../dtos/category.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class CategorysController {
  constructor(private readonly categorysService: CategorysService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreateCategoryDTO;
      const entity = await this.categorysService.createCategory(data);
      sendCreated(res, entity, 'Category creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Category:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.categorysService.getCategoryById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Category:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.categorysService.getAllCategorys();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Categorys:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdateCategoryDTO;
      const entity = await this.categorysService.updateCategory(id, data);
      sendSuccess(res, entity, 'Category actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Category:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.categorysService.deleteCategory(id);
      sendSuccess(res, null, 'Category eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Category:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default CategorysController;
