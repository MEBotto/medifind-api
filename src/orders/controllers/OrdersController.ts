import { Request, Response } from 'express';
import OrdersService from '../services/OrdersService';
import { CreateOrderDTO, UpdateOrderDTO } from '../dtos/order.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class OrdersController {
  constructor(private readonly ordersService: OrdersService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreateOrderDTO;
      const entity = await this.ordersService.createOrder(data);
      sendCreated(res, entity, 'Order creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Order:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.ordersService.getOrderById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Order:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.ordersService.getAllOrders();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Orders:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdateOrderDTO;
      const entity = await this.ordersService.updateOrder(id, data);
      sendSuccess(res, entity, 'Order actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Order:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.ordersService.deleteOrder(id);
      sendSuccess(res, null, 'Order eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Order:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default OrdersController;
