import { Request, Response } from 'express';
import CustomersService from '../services/CustomersService';
import { CreateCustomerDTO, UpdateCustomerDTO } from '../dtos/customer.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class CustomersController {
  constructor(private readonly customersService: CustomersService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreateCustomerDTO;
      const entity = await this.customersService.createCustomer(data);
      sendCreated(res, entity, 'Customer creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Customer:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.customersService.getCustomerById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Customer:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.customersService.getAllCustomers();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Customers:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdateCustomerDTO;
      const entity = await this.customersService.updateCustomer(id, data);
      sendSuccess(res, entity, 'Customer actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Customer:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.customersService.deleteCustomer(id);
      sendSuccess(res, null, 'Customer eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Customer:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default CustomersController;
