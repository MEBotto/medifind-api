import { Request, Response } from 'express';
import PersonsService from '../services/PersonsService';
import { CreatePersonDTO, UpdatePersonDTO } from '../dtos/person.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class PersonsController {
  constructor(private readonly personsService: PersonsService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreatePersonDTO;
      const entity = await this.personsService.createPerson(data);
      sendCreated(res, entity, 'Person creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Person:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.personsService.getPersonById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Person:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.personsService.getAllPersons();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Persons:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdatePersonDTO;
      const entity = await this.personsService.updatePerson(id, data);
      sendSuccess(res, entity, 'Person actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Person:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.personsService.deletePerson(id);
      sendSuccess(res, null, 'Person eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Person:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default PersonsController;
