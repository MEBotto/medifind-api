import { Request, Response } from 'express';
import PermissionsService from '../services/PermissionsService';
import { CreatePermissionDTO, UpdatePermissionDTO } from '../dtos/permission.dto';
import { AppError } from '@/middleware/error.middleware';
import { logger } from '@/utils/logger';
import { sendSuccess, sendCreated, sendError } from '@/utils/api.utils';

class PermissionsController {
  constructor(private readonly permissionsService: PermissionsService) {}

  create = async (req: Request, res: Response): Promise<void> => {
    try {
      const data = req.body as CreatePermissionDTO;
      const entity = await this.permissionsService.createPermission(data);
      sendCreated(res, entity, 'Permission creado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode, error.validationErrors);
        return;
      }
      logger.error('Error en create Permission:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getById = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const entity = await this.permissionsService.getPermissionById(id);
      sendSuccess(res, entity);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getById Permission:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  getAll = async (req: Request, res: Response): Promise<void> => {
    try {
      const entities = await this.permissionsService.getAllPermissions();
      sendSuccess(res, entities);
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en getAll Permissions:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  update = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      const data = req.body as UpdatePermissionDTO;
      const entity = await this.permissionsService.updatePermission(id, data);
      sendSuccess(res, entity, 'Permission actualizado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en update Permission:', error);
      sendError(res, 'Error interno del servidor');
    }
  };

  delete = async (req: Request, res: Response): Promise<void> => {
    try {
      const { id } = req.params;
      await this.permissionsService.deletePermission(id);
      sendSuccess(res, null, 'Permission eliminado exitosamente');
    } catch (error) {
      if (error instanceof AppError) {
        sendError(res, error.message, error.statusCode);
        return;
      }
      logger.error('Error en delete Permission:', error);
      sendError(res, 'Error interno del servidor');
    }
  };
}

export default PermissionsController;
